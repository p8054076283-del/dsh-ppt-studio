// Assembles `lib/client.js` — the browser bundle — in the same hand-written idiom as
// the locally proven bundles (classic script → ModuleLoader factory → CJS exports).
//
// Sources, in order:
//   src/bundle/prelude.js   constants, diagnostics, styles, icon
//   src/client/render.js    deck model / layouts / slide HTML (ported from the old extension)
//   src/bundle/markdown.js  Markdown → React elements for the chat transcript
//   src/bundle/panel.js     the panel page component
//   src/bundle/register.js  slot registration + exports
import { readFileSync, writeFileSync } from 'node:fs'

const root = new URL('.', import.meta.url)
const at = (path) => new URL(path, root)
const read = (path) => readFileSync(at(path), 'utf8')

/** Strip the `define('<name>', function (React) { ... })` wrapper, keeping the body. */
function bodyOf(path, name) {
  const source = read(path)
  const start = source.indexOf(`define('${name}'`)
  if (start < 0) throw new Error(`${path}: no define('${name}') wrapper`)
  const firstBrace = source.indexOf('{', start)
  const lastBrace = source.lastIndexOf('})')
  if (firstBrace < 0 || lastBrace < firstBrace) throw new Error(`${path}: unexpected wrapper shape`)
  return source.slice(firstBrace + 1, lastBrace).replace(/^\s*'use strict'\s*$/m, '')
}

const prelude = read('src/bundle/prelude.js')
const render = bodyOf('src/client/render.js', 'render')
const markdown = read('src/bundle/markdown.js')
const panel = read('src/bundle/panel.js')
const chat = read('src/bundle/chat.js')
const register = read('src/bundle/register.js')

const output = `/* dsh-ppt-studio browser bundle — generated by build2.mjs; edit src/bundle/*.js or
 * src/client/render.js and re-run \`node build2.mjs\`.
 */
window.__ModuleLoader__.load({
  id: 'dsh-ppt-studio',
  factory: (require) => {
    var react = require('react')
    var h = react.createElement
    var module = { exports: {} }
    var exports = module.exports
    Object.defineProperty(exports, Symbol.toStringTag, { value: 'Module' })

${prelude}
    /* ============================ render module ============================ */
    var Render = (function () {
${render}
    })()

${markdown}
${panel}
${chat}

${register}
    return module.exports
  },
})
`

writeFileSync(at('lib/client.js'), output)
console.log(`lib/client.js built: ${output.length} bytes`)
